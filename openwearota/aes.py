"""Minimal AES-256-ECB encrypt-only implementation (pure Python, no dependencies).

Used by the RealSil DFU driver to encrypt the START_DFU metadata header and
firmware data blocks.  Only encrypt() is needed — the watch never sends
encrypted data back that we'd need to decrypt.

This is a textbook AES implementation: SubBytes, ShiftRows, MixColumns, AddRoundKey,
14 rounds for AES-256.  It operates on single 16-byte blocks (ECB mode).
Performance is adequate for OTA use — the bottleneck is BLE throughput, not AES.
"""
